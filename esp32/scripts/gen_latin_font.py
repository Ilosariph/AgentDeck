#!/usr/bin/env python3
"""Render Montserrat Medium's Latin glyphs into an LVGL font (fmt_txt, 4 bpp).

LVGL's built-in Montserrat faces stop at ASCII, so titles like "Ärzte" or
"Café – Live" lost their letters. These faces sit in the fallback chain
behind them: Montserrat (ASCII) -> font_latin_<size> -> Noto KR.

With --ascii-tabular it renders printable ASCII instead, every digit on the
widest digit's advance (tabular figures), for times that must not shift:
font_tabular_12.

Same output shape as lv_font_conv --format lvgl --no-compress, rendered with
FreeType instead:

    nix shell --impure --expr 'with import <nixpkgs> {}; python3.withPackages (p: [p.freetype-py])' \\
      -c python3 esp32/scripts/gen_latin_font.py <Montserrat-Medium.ttf> 12 esp32/src/ui/fonts/font_latin_12.c
"""
import sys

import freetype

# Latin-1 Supplement + Latin Extended-A, typographic quotes/dashes, bullet,
# ellipsis, euro, trademark.
RANGES = [(0xA0, 0x17F), (0x2013, 0x2014), (0x2018, 0x201E), (0x2022, 0x2022),
          (0x2026, 0x2026), (0x20AC, 0x20AC), (0x2122, 0x2122)]


ASCII = [(0x20, 0x7E)]


def render(path: str, size: int, ranges=RANGES, tabular=False):
    face = freetype.Face(path)
    face.set_pixel_sizes(0, size)
    glyphs = []
    for lo, hi in ranges:
        for cp in range(lo, hi + 1):
            if not face.get_char_index(cp):
                continue
            face.load_char(cp, freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_NORMAL)
            g = face.glyph
            bm = g.bitmap
            px = []
            for y in range(bm.rows):
                row = bm.buffer[y * bm.pitch:y * bm.pitch + bm.width]
                px.extend(v >> 4 for v in row)
            if len(px) % 2:
                px.append(0)
            data = bytes((px[i] << 4) | px[i + 1] for i in range(0, len(px), 2))
            glyphs.append({
                'cp': cp, 'data': data, 'adv_w': round(g.advance.x / 64 * 16),
                'box_w': bm.width, 'box_h': bm.rows,
                'ofs_x': g.bitmap_left, 'ofs_y': g.bitmap_top - bm.rows,
            })
    if tabular:
        # Digits on one advance, each centred in it; Montserrat ships tnum only
        # as an OpenType feature, which FreeType alone does not apply.
        digits = [g for g in glyphs if 0x30 <= g['cp'] <= 0x39]
        adv = max(g['adv_w'] for g in digits)
        for g in digits:
            g['ofs_x'] += round((adv - g['adv_w']) / 16 / 2)
            g['adv_w'] = adv
    asc = face.size.ascender / 64
    desc = face.size.descender / 64
    return glyphs, round(asc - desc), round(-desc)


def emit(glyphs, line_height, base_line, size, name, src):
    what = ('printable ASCII, tabular digits' if name.startswith('font_tabular')
            else 'Latin-1, Latin Extended-A, quotes, dashes')
    out = [f'''/*******************************************************************************
 * Size: {size} px
 * Bpp: 4
 * Generated by esp32/scripts/gen_latin_font.py from {src.split('/')[-1]}
 * (Montserrat, SIL OFL 1.1): {what}.
 ******************************************************************************/

#include "lvgl.h"

static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {{''']
    index = 0
    for g in glyphs:
        g['index'] = index
        index += len(g['data'])
        ch = chr(g['cp'])
        out.append(f'    /* U+{g["cp"]:04X} "{ch if ch.isprintable() and ch not in "*/\\" else ""}" */')
        hexes = [f'0x{b:x}' for b in g['data']]
        for i in range(0, len(hexes), 8):
            out.append('    ' + ', '.join(hexes[i:i + 8]) + ',')
        out.append('')
    if index == 0:
        out.append('    0x0,')
    out.append('};\n')
    out.append('static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {')
    out.append('    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id = 0 reserved */,')
    for g in glyphs:
        out.append(f'    {{.bitmap_index = {g["index"]}, .adv_w = {g["adv_w"]}, .box_w = {g["box_w"]}, '
                   f'.box_h = {g["box_h"]}, .ofs_x = {g["ofs_x"]}, .ofs_y = {g["ofs_y"]}}},')
    out.append('};\n')
    # Consecutive code points share one range.
    cmaps = []
    for gid, g in enumerate(glyphs, start=1):
        if cmaps and cmaps[-1][0] + cmaps[-1][1] == g['cp']:
            cmaps[-1][1] += 1
        else:
            cmaps.append([g['cp'], 1, gid])
    out.append('static const lv_font_fmt_txt_cmap_t cmaps[] = {')
    for start, length, gid in cmaps:
        out.append(f'    {{.range_start = {start}, .range_length = {length}, .glyph_id_start = {gid}, '
                   '.unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, '
                   '.type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},')
    out.append('};\n')
    out.append(f'''static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .kern_dsc = NULL,
    .kern_scale = 0,
    .cmap_num = {len(cmaps)},
    .bpp = 4,
    .kern_classes = 0,
    .bitmap_format = 0,
}};

const lv_font_t {name} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {line_height},
    .base_line = {base_line},
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = -1,
    .underline_thickness = 1,
    .dsc = &font_dsc,
    .fallback = NULL,
    .user_data = NULL,
}};
''')
    return '\n'.join(out)


def main():
    args = [a for a in sys.argv[1:] if a != '--ascii-tabular']
    tabular = len(args) != len(sys.argv) - 1
    if len(args) != 3:
        sys.exit(__doc__)
    path, size, dest = args[0], int(args[1]), args[2]
    glyphs, lh, bl = render(path, size, ASCII if tabular else RANGES, tabular)
    name = dest.rsplit('/', 1)[-1].removesuffix('.c')
    with open(dest, 'w', encoding='utf-8') as f:
        f.write(emit(glyphs, lh, bl, size, name, path))
    print(f'{dest}: {len(glyphs)} glyphs, line_height {lh}, base_line {bl}')


if __name__ == '__main__':
    main()
